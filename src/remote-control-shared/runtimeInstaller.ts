/**
 * Installs the Remote Control runtime into a stable, version-independent
 * location and writes the "how to connect" manifest, so that any agent can use
 * ClaUi right after the extension is installed:
 *
 *   ~/.claui/remote-control/bin/<version>/{mcp-server,cli,client}.js   copied bundles
 *   ~/.claui/remote-control/bin/current.json                           active version
 *   ~/.claui/remote-control/bin/claui-mcp.js | claui.js | claui-client.js   stable launchers
 *   ~/.claui/remote-control/bin/claui_client.py                        Python client
 *   ~/.claui/remote-control/connection.json + CONNECT.md               connection manifest
 *
 * Used by the extension on every activation and by `claui.js install`.
 * Must never import `vscode`.
 */

export const RUNTIME_BUNDLES = ['mcp-server.js', 'cli.js', 'client.js'];

export interface NodeCommand {
  command: string;
  env?: Record<string, string>;
}

export interface InstallResult {
  version: string;
  dir: string;
  /** False when a newer version was already current (this install only added its own directory). */
  becameCurrent: boolean;
}

/** Numeric dotted-version compare ("0.1.10" > "0.1.9"). */
export function compareVersions(a: string, b: string): number {
  const pa = a.split(/[.-]/).map((p) => Number.parseInt(p, 10) || 0);
  const pb = b.split(/[.-]/).map((p) => Number.parseInt(p, 10) || 0);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const diff = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (diff !== 0) {
      return diff;
    }
  }
  return 0;
}

function writeIfChanged(filePath: string, content: string | Buffer): boolean {
  const next = typeof content === 'string' ? Buffer.from(content, 'utf8') : content;
  if (fs.existsSync(filePath)) {
    const current = fs.readFileSync(filePath);
    if (crypto.createHash('sha256').update(current).digest('hex') === crypto.createHash('sha256').update(next).digest('hex')) {
      return false;
    }
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const tmp = `${filePath}.${process.pid}.${Date.now()}.tmp`;
  fs.writeFileSync(tmp, next);
  fs.renameSync(tmp, filePath);
  return true;
}

function launcherSource(entry: string, title: string, kind: 'executable' | 'library'): string {
  const failure =
    kind === 'executable'
      ? `  process.stderr.write('ClaUi Remote Control runtime is not installed. Open VS Code with the ClaUi extension once.\\n');\n  process.exit(1);\n`
      : `  throw new Error('ClaUi Remote Control runtime is not installed. Open VS Code with the ClaUi extension once.');\n`;
  return (
    (kind === 'executable' ? '#!/usr/bin/env node\n' : '') +
    `// ${title}.\n` +
    `// Generated by the ClaUi VS Code extension: a stable entry point that loads the\n` +
    `// newest installed runtime, so configs that reference this file survive updates.\n` +
    `'use strict';\n` +
    `const fs = require('fs');\n` +
    `const path = require('path');\n` +
    `let current;\n` +
    `try {\n` +
    `  current = JSON.parse(fs.readFileSync(path.join(__dirname, 'current.json'), 'utf8'));\n` +
    `} catch (err) {\n` +
    failure +
    `}\n` +
    (kind === 'library'
      ? `module.exports = require(path.join(current.dir, ${JSON.stringify(entry)}));\n`
      : `require(path.join(current.dir, ${JSON.stringify(entry)}));\n`)
  );
}

/** Keep the current and the newest previous version directory; delete older ones. */
function pruneOldRuntimes(binDir: string, keepVersion: string): void {
  try {
    const dirs = fs
      .readdirSync(binDir, { withFileTypes: true })
      .filter((d) => d.isDirectory() && d.name !== keepVersion && /^\d+\.\d+\.\d+/.test(d.name))
      .map((d) => d.name)
      .sort((a, b) => compareVersions(b, a));
    for (const old of dirs.slice(1)) {
      fs.rmSync(path.join(binDir, old), { recursive: true, force: true });
    }
  } catch {
    /* best effort */
  }
}

/**
 * Copy the runtime bundles from `sourceDir` into `<binDir>/<version>/` and
 * point the stable launchers at the newest installed version (an older
 * extension instance never downgrades `current.json`).
 */
export function installRuntime(sourceDir: string, version: string, binDir: string = BIN_DIR): InstallResult {
  const targetDir = path.join(binDir, version);
  for (const bundle of RUNTIME_BUNDLES) {
    const src = path.join(sourceDir, bundle);
    if (!fs.existsSync(src)) {
      throw new Error(`Runtime bundle missing: ${src}`);
    }
    writeIfChanged(path.join(targetDir, bundle), fs.readFileSync(src));
  }

  // Two ClaUi builds (e.g. VS Code Stable + Insiders) may install at the same
  // time: read-compare-write current.json under a lock so an older build can
  // never overwrite a newer one that won the race.
  const outcome = withInstallLock(binDir, () => {
    const currentFile = path.join(binDir, 'current.json');
    let current: { version?: string; dir?: string } | null = null;
    try {
      current = JSON.parse(fs.readFileSync(currentFile, 'utf8'));
    } catch {
      current = null;
    }
    const becameCurrent =
      !current?.version || !current.dir || !fs.existsSync(current.dir) || compareVersions(version, current.version) >= 0;
    if (becameCurrent) {
      writeIfChanged(currentFile, JSON.stringify({ version, dir: targetDir }, null, 2));
    }
    return { becameCurrent, currentVersion: becameCurrent ? version : String(current?.version ?? version) };
  });

  writeIfChanged(path.join(binDir, 'claui-mcp.js'), launcherSource('mcp-server.js', 'ClaUi Remote Control MCP server (stdio)', 'executable'));
  writeIfChanged(path.join(binDir, 'claui.js'), launcherSource('cli.js', 'ClaUi Remote Control command-line client', 'executable'));
  writeIfChanged(path.join(binDir, 'claui-client.js'), launcherSource('client.js', 'ClaUi Remote Control Node.js client library', 'library'));
  if (outcome.becameCurrent) {
    writeIfChanged(path.join(binDir, 'claui_client.py'), pythonClientSource());
  }
  pruneOldRuntimes(binDir, outcome.currentVersion);
  return { version, dir: targetDir, becameCurrent: outcome.becameCurrent };
}

function sleepSync(ms: number): void {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

/**
 * Run `fn` holding an exclusive lock file in `binDir`. A lock older than 30 s
 * is treated as left over by a crashed installer. After 5 s of waiting the
 * work runs anyway (activation must never block on this).
 */
function withInstallLock<T>(binDir: string, fn: () => T): T {
  fs.mkdirSync(binDir, { recursive: true });
  const lockPath = path.join(binDir, '.install.lock');
  const deadline = Date.now() + 5000;
  let fd: number | null = null;
  while (fd === null) {
    try {
      fd = fs.openSync(lockPath, 'wx');
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== 'EEXIST') {
        break;
      }
      try {
        if (Date.now() - fs.statSync(lockPath).mtimeMs > 30_000) {
          fs.unlinkSync(lockPath);
          continue;
        }
      } catch {
        continue;
      }
      if (Date.now() > deadline) {
        break;
      }
      sleepSync(50);
    }
  }
  try {
    return fn();
  } finally {
    if (fd !== null) {
      fs.closeSync(fd);
      try {
        fs.unlinkSync(lockPath);
      } catch {
        /* already gone */
      }
    }
  }
}

/**
 * The command MCP clients should run: the absolute `node` on PATH when there
 * is one, otherwise `fallback` (the extension passes VS Code's own Electron
 * binary with ELECTRON_RUN_AS_NODE=1).
 */
export function resolveNodeCommand(fallback: NodeCommand): NodeCommand {
  try {
    const probe = process.platform === 'win32' ? 'where' : 'which';
    const res = spawnSync(probe, ['node'], { encoding: 'utf8', timeout: 4000, windowsHide: true });
    const first = (res.stdout || '')
      .split(/\r?\n/)
      .map((l) => l.trim())
      .find((l) => l && fs.existsSync(l));
    if (res.status === 0 && first) {
      return { command: first };
    }
  } catch {
    /* fall through */
  }
  return fallback;
}

/** The node running this process (node itself, or Electron in node mode). */
export function currentProcessNodeCommand(): NodeCommand {
  const electron = (process.versions as Record<string, string | undefined>).electron;
  return electron ? { command: process.execPath, env: { ELECTRON_RUN_AS_NODE: '1' } } : { command: process.execPath };
}

export interface StdioServerEntry {
  command: string;
  args: string[];
  env?: Record<string, string>;
}

export function stdioServerEntry(node: NodeCommand, binDir: string = BIN_DIR): StdioServerEntry {
  return { command: node.command, args: [path.join(binDir, 'claui-mcp.js')], ...(node.env ? { env: node.env } : {}) };
}

function quote(value: string): string {
  return `"${value.replace(/"/g, '\\"')}"`;
}

/** Ready-to-paste MCP client configurations. */
export function clientConfigs(node: NodeCommand, binDir: string = BIN_DIR): Record<string, { where: string; config: string }> {
  const entry = stdioServerEntry(node, binDir);
  // `-e` is variadic in `claude mcp add`: the server name must come before it.
  const envFlags = Object.entries(entry.env ?? {}).map(([k, v]) => `-e ${k}=${v} `).join('');
  // JSON strings are valid TOML basic strings (escapes quotes / backslashes / apostrophes correctly).
  const toml = (value: string): string => JSON.stringify(value);
  const tomlEnv = entry.env
    ? `env = { ${Object.entries(entry.env).map(([k, v]) => `${k} = ${toml(v)}`).join(', ')} }\n`
    : '';
  const mcpServers = JSON.stringify({ mcpServers: { [MCP_SERVER_NAME]: entry } }, null, 2);
  return {
    'claude-code': {
      where: 'Run in a terminal (user scope = every project). Or: node claui.js register',
      config: `claude mcp add --scope user ${MCP_SERVER_NAME} ${envFlags}-- ${quote(entry.command)} ${quote(entry.args[0])}`,
    },
    'claude-desktop': {
      where: process.platform === 'win32' ? '%APPDATA%\\Claude\\claude_desktop_config.json' : '~/Library/Application Support/Claude/claude_desktop_config.json',
      config: mcpServers,
    },
    cursor: { where: '~/.cursor/mcp.json (or <project>/.cursor/mcp.json)', config: mcpServers },
    windsurf: { where: '~/.codeium/windsurf/mcp_config.json', config: mcpServers },
    codex: {
      where: '~/.codex/config.toml',
      config: `[mcp_servers.${MCP_SERVER_NAME}]\ncommand = ${toml(entry.command)}\nargs = [${toml(entry.args[0])}]\n${tomlEnv}`,
    },
    vscode: {
      where: 'Nothing to do inside VS Code: ClaUi registers the server itself (MCP: List Servers). For another editor using this format: .vscode/mcp.json',
      config: JSON.stringify({ servers: { [MCP_SERVER_NAME]: { type: 'stdio', ...entry } } }, null, 2),
    },
    generic: { where: 'Any MCP client that accepts an mcpServers JSON block (Cline, Continue, custom agents...)', config: mcpServers },
  };
}

export interface ConnectionInfo {
  app: 'ClaUi';
  description: string;
  runtimeVersion: string;
  generatedAt: string;
  mcp: {
    serverName: string;
    transport: 'stdio';
    command: string;
    args: string[];
    env?: Record<string, string>;
    clients: Record<string, { where: string; config: string }>;
  };
  cli: { command: string; args: string[]; help: string };
  libraries: { node: string; python: string };
  http: {
    note: string;
    tokenFile: string;
    instancesDir: string;
    requestsDir: string;
    auth: string;
    routes: Record<string, string>;
  };
  docs: string;
  /** Full agent integration guide shipped inside the extension package (absolute path), when known. */
  guide?: string;
}

export function buildConnectionInfo(
  node: NodeCommand,
  version: string,
  binDir: string = BIN_DIR,
  guidePath?: string,
): ConnectionInfo {
  const entry = stdioServerEntry(node, binDir);
  const cliPath = path.join(binDir, 'claui.js');
  return {
    app: 'ClaUi',
    description:
      'Control the ClaUi VS Code extension (multi-tab Claude Code / Codex chats): open tabs, send prompts and get replies, ' +
      'answer approvals, change models and settings, read history, follow events. VS Code with ClaUi must be running; ' +
      'its control server starts automatically on the first request.',
    runtimeVersion: version,
    generatedAt: new Date().toISOString(),
    mcp: {
      serverName: MCP_SERVER_NAME,
      transport: 'stdio',
      command: entry.command,
      args: entry.args,
      ...(entry.env ? { env: entry.env } : {}),
      clients: clientConfigs(node, binDir),
    },
    cli: { command: node.command, args: [cliPath], help: `${quote(node.command)} ${quote(cliPath)} help` },
    libraries: { node: path.join(binDir, 'claui-client.js'), python: path.join(binDir, 'claui_client.py') },
    http: {
      note:
        'Each VS Code window has a record in instancesDir. If its "serving" is false, write any file named ' +
        '"<instanceId>__<anything>.json" into requestsDir and wait for "serving": true (the bundled clients do this).',
      tokenFile: TOKEN_FILE,
      instancesDir: INSTANCES_DIR,
      requestsDir: REQUESTS_DIR,
      auth: 'Authorization: Bearer <contents of tokenFile>',
      routes: {
        mcp: `POST http://127.0.0.1:<port>${ROUTES.mcp} (MCP Streamable HTTP, JSON responses)`,
        tools: `GET http://127.0.0.1:<port>${ROUTES.tools}`,
        call: `POST http://127.0.0.1:<port>${ROUTES.toolPrefix}<tool> with a JSON arguments body`,
        events: `GET http://127.0.0.1:<port>${ROUTES.events}?since=<seq>&wait=<sec>`,
        eventStream: `GET http://127.0.0.1:<port>${ROUTES.eventStream} (SSE)`,
        status: `GET http://127.0.0.1:<port>${ROUTES.status}`,
      },
    },
    docs: CONNECT_DOC,
    ...(guidePath ? { guide: guidePath } : {}),
  };
}

function connectDoc(info: ConnectionInfo): string {
  const c = info.mcp.clients;
  const fence = (lang: string, body: string): string => `\`\`\`${lang}\n${body.trimEnd()}\n\`\`\``;
  return [
    '# ClaUi Remote Control - how to connect',
    '',
    info.description,
    '',
    `Runtime ${info.runtimeVersion}. Generated by the ClaUi VS Code extension; machine-readable copy: ${CONNECTION_FILE}`,
    ...(info.guide ? ['', `Full guide (all agents, every tool, troubleshooting): ${info.guide}`] : []),
    '',
    '## MCP (recommended for agents)',
    '',
    'stdio server:',
    '',
    fence('json', JSON.stringify({ command: info.mcp.command, args: info.mcp.args, ...(info.mcp.env ? { env: info.mcp.env } : {}) }, null, 2)),
    '',
    'Claude Code:',
    '',
    fence('', c['claude-code'].config),
    '',
    `Claude Desktop / Cursor / Windsurf / generic (${c['claude-desktop'].where}):`,
    '',
    fence('json', c.generic.config),
    '',
    `Codex CLI (${c.codex.where}):`,
    '',
    fence('toml', c.codex.config),
    '',
    'Inside VS Code nothing is needed: ClaUi registers this MCP server with VS Code itself.',
    '',
    'Start with the tools `get_status` / `list_tabs`; `send_message` sends a prompt exactly like typing in the chat and waits for the reply.',
    '',
    '## CLI',
    '',
    fence('', [
      `${info.cli.help}`,
      `${quote(info.cli.command)} ${quote(info.cli.args[0])} tabs`,
      `${quote(info.cli.command)} ${quote(info.cli.args[0])} send "Run the tests and summarize failures"`,
      `${quote(info.cli.command)} ${quote(info.cli.args[0])} register        # add the MCP server to Claude Code`,
      `${quote(info.cli.command)} ${quote(info.cli.args[0])} mcp-config      # configs for other MCP clients`,
      `${quote(info.cli.command)} ${quote(info.cli.args[0])} doctor          # diagnose the connection`,
    ].join('\n')),
    '',
    '## Libraries',
    '',
    `Node.js: \`const claui = require(${JSON.stringify(info.libraries.node)}).connect(); await claui.call('list_tabs');\``,
    '',
    `Python: add \`${path.dirname(info.libraries.python)}\` to sys.path, then \`from claui_client import ClauiClient; ClauiClient().call("list_tabs")\``,
    '',
    '## Raw HTTP',
    '',
    info.http.note,
    '',
    ...Object.values(info.http.routes).map((r) => `- ${r}`),
    `- Auth: ${info.http.auth} (token file: ${info.http.tokenFile})`,
    '',
    '## Notes',
    '',
    '- VS Code with ClaUi must be running. Calls go to the window whose folder contains your working directory, else the most recently focused one (override: CLAUI_INSTANCE=<instanceId | folder | name>).',
    '- The window starts its control server on the first request (setting claudeMirror.remoteControl.mode: auto | on | off).',
    '- Anyone with the token can run prompts as this user. Read-only mode: claudeMirror.remoteControl.accessLevel = readOnly.',
    '',
  ].join('\n');
}

/** Write connection.json + CONNECT.md (skipped when unchanged apart from the timestamp). */
export function writeConnectionFiles(info: ConnectionInfo, home: string = REMOTE_CONTROL_HOME): void {
  const jsonPath = path.join(home, path.basename(CONNECTION_FILE));
  const docPath = path.join(home, path.basename(CONNECT_DOC));
  let previous: ConnectionInfo | null = null;
  try {
    previous = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  } catch {
    previous = null;
  }
  const comparable = (i: ConnectionInfo | null) => (i ? JSON.stringify({ ...i, generatedAt: '' }) : '');
  if (comparable(previous) !== comparable(info)) {
    writeIfChanged(jsonPath, JSON.stringify(info, null, 2));
  }
  writeIfChanged(docPath, connectDoc(info));
}

