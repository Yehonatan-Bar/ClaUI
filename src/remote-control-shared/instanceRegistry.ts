import * as crypto from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
import { INSTANCES_DIR, REMOTE_CONTROL_HOME, TOKEN_FILE, type InstanceInfo } from './protocol';

/**
 * Discovery of live ClaUi windows + the shared auth token.
 *
 * Every VS Code window (extension host) with remote control enabled writes
 * `<INSTANCES_DIR>/<instanceId>.json`; readers skip (and garbage-collect)
 * records whose owning process is gone. Must never import `vscode`.
 */

export interface RegistryPaths {
  instancesDir: string;
  tokenFile: string;
}

export const DEFAULT_REGISTRY_PATHS: RegistryPaths = {
  instancesDir: INSTANCES_DIR,
  tokenFile: TOKEN_FILE,
};

/** True when a process with this pid exists (EPERM = exists but not ours to signal). */
export function isProcessAlive(pid: number): boolean {
  if (!Number.isInteger(pid) || pid <= 0) {
    return false;
  }
  try {
    process.kill(pid, 0);
    return true;
  } catch (err) {
    return (err as NodeJS.ErrnoException).code === 'EPERM';
  }
}

function ensureDir(dir: string): void {
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
}

/** Write a file atomically (temp + rename) with owner-only permissions where the OS supports it. */
function writeFileAtomic(filePath: string, content: string): void {
  ensureDir(path.dirname(filePath));
  const tmpPath = `${filePath}.${process.pid}.${Date.now()}.tmp`;
  fs.writeFileSync(tmpPath, content, { encoding: 'utf8', mode: 0o600 });
  fs.renameSync(tmpPath, filePath);
}

export function instanceFilePath(instanceId: string, paths: RegistryPaths = DEFAULT_REGISTRY_PATHS): string {
  // instanceId is generated by us (hex); sanitize anyway so it can never escape the directory.
  return path.join(paths.instancesDir, `${instanceId.replace(/[^a-zA-Z0-9_-]/g, '')}.json`);
}

export function writeInstance(info: InstanceInfo, paths: RegistryPaths = DEFAULT_REGISTRY_PATHS): void {
  writeFileAtomic(instanceFilePath(info.instanceId, paths), JSON.stringify(info, null, 2));
}

export function removeInstance(instanceId: string, paths: RegistryPaths = DEFAULT_REGISTRY_PATHS): void {
  try {
    fs.unlinkSync(instanceFilePath(instanceId, paths));
  } catch {
    /* already gone */
  }
}

function isInstanceInfo(value: unknown): value is InstanceInfo {
  const v = value as Partial<InstanceInfo> | null;
  return (
    !!v &&
    typeof v.instanceId === 'string' &&
    typeof v.pid === 'number' &&
    typeof v.port === 'number' &&
    Array.isArray(v.workspaceFolders)
  );
}

/**
 * All live instances, most recently focused first. Records of dead processes
 * are deleted as a side effect (they are leftovers of crashed windows).
 */
export function listInstances(
  paths: RegistryPaths = DEFAULT_REGISTRY_PATHS,
  aliveCheck: (pid: number) => boolean = isProcessAlive,
): InstanceInfo[] {
  let entries: string[];
  try {
    entries = fs.readdirSync(paths.instancesDir);
  } catch {
    return [];
  }
  const instances: InstanceInfo[] = [];
  for (const entry of entries) {
    if (!entry.endsWith('.json')) {
      continue;
    }
    const filePath = path.join(paths.instancesDir, entry);
    let parsed: unknown;
    try {
      parsed = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    } catch {
      continue; // half-written or corrupt; the writer replaces it atomically
    }
    if (!isInstanceInfo(parsed)) {
      continue;
    }
    if (!aliveCheck(parsed.pid)) {
      try {
        fs.unlinkSync(filePath);
      } catch {
        /* ignore */
      }
      continue;
    }
    instances.push(parsed);
  }
  const rank = (i: InstanceInfo): number => Date.parse(i.lastFocusedAt || i.startedAt) || 0;
  return instances.sort((a, b) => rank(b) - rank(a));
}

/** Case/separator-insensitive path form used for comparisons (Windows paths are case-insensitive). */
export function normalizePathForCompare(p: string): string {
  let out = p.replace(/\\/g, '/').replace(/\/+$/, '');
  if (process.platform === 'win32' || /^[a-zA-Z]:\//.test(out)) {
    out = out.toLowerCase();
  }
  return out;
}

function isInsideOrEqual(child: string, parent: string): boolean {
  const c = normalizePathForCompare(child);
  const p = normalizePathForCompare(parent);
  return c === p || c.startsWith(`${p}/`);
}

/**
 * Pick the instance a client should talk to.
 *  1. `preferred` (instanceId exact, then workspace path/name match),
 *  2. the window whose workspace contains `cwd`,
 *  3. the most recently active window.
 */
export function selectInstance(
  instances: InstanceInfo[],
  opts: { preferred?: string; cwd?: string } = {},
): InstanceInfo | undefined {
  if (instances.length === 0) {
    return undefined;
  }
  const preferred = opts.preferred?.trim();
  if (preferred) {
    const byId = instances.find((i) => i.instanceId === preferred);
    if (byId) {
      return byId;
    }
    const byPath = instances.find((i) => i.workspaceFolders.some((f) => isInsideOrEqual(preferred, f) || isInsideOrEqual(f, preferred)));
    if (byPath) {
      return byPath;
    }
    const needle = preferred.toLowerCase();
    return instances.find(
      (i) =>
        i.workspaceName.toLowerCase().includes(needle) ||
        i.workspaceFolders.some((f) => normalizePathForCompare(f).includes(normalizePathForCompare(preferred))),
    );
  }
  if (opts.cwd) {
    const cwd = opts.cwd;
    // Deepest matching workspace wins (nested workspaces).
    const matches = instances
      .flatMap((i) => i.workspaceFolders.filter((f) => isInsideOrEqual(cwd, f)).map((f) => ({ i, depth: normalizePathForCompare(f).length })))
      .sort((a, b) => b.depth - a.depth);
    if (matches.length > 0) {
      return matches[0].i;
    }
  }
  return instances[0];
}

