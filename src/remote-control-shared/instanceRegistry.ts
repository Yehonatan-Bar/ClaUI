export function readToken(paths: RegistryPaths = DEFAULT_REGISTRY_PATHS): string | null {
  try {
    const token = fs.readFileSync(paths.tokenFile, 'utf8').trim();
    return token.length >= 32 ? token : null;
  } catch {
    return null;
  }
}

/** Returns the existing token, creating one on first use. */
export function ensureToken(paths: RegistryPaths = DEFAULT_REGISTRY_PATHS): string {
  const existing = readToken(paths);
  if (existing) {
    return existing;
  }
  return regenerateToken(paths);
}

/** Replace the token (old MCP client configs that embed it stop working). */
export function regenerateToken(paths: RegistryPaths = DEFAULT_REGISTRY_PATHS): string {
  const token = crypto.randomBytes(32).toString('hex');
  writeFileAtomic(paths.tokenFile, `${token}\n`);
  return token;
}

/** Constant-time token comparison. */
export function tokensEqual(a: string, b: string): boolean {
  const left = Buffer.from(a, 'utf8');
  const right = Buffer.from(b, 'utf8');
  if (left.length !== right.length) {
    // Still burn a comparison so timing does not reveal the length mismatch early.
    crypto.timingSafeEqual(left, left);
    return false;
  }
  return crypto.timingSafeEqual(left, right);
}

export function newInstanceId(): string {
  return crypto.randomBytes(8).toString('hex');
}

